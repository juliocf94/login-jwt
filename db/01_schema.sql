-- ---------------------------------------------------------------------
-- CONTRIBUYENTE: la tabla del CRUD
-- ---------------------------------------------------------------------
CREATE TABLE contribuyente (
    id      NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nit     VARCHAR2(20)  NOT NULL,
    nombre  VARCHAR2(150) NOT NULL,
    email   VARCHAR2(150),
    tipo    VARCHAR2(10)  DEFAULT 'PERSONA' NOT NULL,
    CONSTRAINT uk_contribuyente_nit  UNIQUE (nit),
    CONSTRAINT ck_contribuyente_tipo CHECK (tipo IN ('PERSONA', 'EMPRESA'))
);

