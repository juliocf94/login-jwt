-- ---------------------------------------------------------------------
-- USUARIO: quién puede entrar y con qué rol
--   password_hash = BCrypt (NUNCA se guarda la contraseña en texto plano)
--   rol           = ADMIN (todo el CRUD) | VIEW (solo listar)
-- ---------------------------------------------------------------------
CREATE TABLE usuario (
    id             NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR2(50)  NOT NULL,
    password_hash  VARCHAR2(100) NOT NULL,
    rol            VARCHAR2(10)  NOT NULL,
    activo         NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT uk_usuario_username UNIQUE (username),
    CONSTRAINT ck_usuario_rol      CHECK (rol IN ('ADMIN', 'VIEW')),
    CONSTRAINT ck_usuario_activo   CHECK (activo IN (0, 1))
);

